# NODE 5: PRINCIPAL PATCH & TEST ENGINEER (Coder Agent)
# =====================================================================
def patch_engineer_node(state: DevSecOpsState) -> dict:
    """Writes the production hotfix patch and comprehensive unit test suite (100% LLM-Generated)."""
    rca = state.get("root_cause_analysis", {}).get("summary", "")
    qa_errors = state.get("qa_test_results") or ""
    current_date = get_current_date_str()
    service = state.get("service_target") or "checkout-api"
    
    prompt = f"""You are a Principal Database & Backend Engineer.
Current Date: {current_date}
Target Service: {service}
RCA: {rca}
Previous QA Errors (if any): {qa_errors}

Generate the production remediation:
Output two distinct markdown code blocks:
Block 1: Database Migration script (e.g. `db.cart_items.createIndex({{ user_id: 1, status: 1 }}, {{ name: "idx_cart_items_user_status" }})` or SQL `CREATE INDEX idx_cart_items_user_status ON cart_items(user_id, status);`)
Block 2: Test Suite verifying that query execution is sub-millisecond with zero deadlocks."""

    response = llm.invoke([
        SystemMessage(content="You are a senior systems engineer. Output the exact code patch in markdown blocks."),
        HumanMessage(content=prompt)
    ])
    
    # 100% DYNAMIC: Extract the actual code generated by the LLM
    extracted = extract_dynamic_code(response.content)
    patch_code = extracted["patch"]
    test_code = extracted["test"]

    current_iter = state.get("iteration_count") or 0

    return {
        "messages": [AIMessage(content=f"💻 [Principal Patch Engineer]: Generated hotfix patch and unit test suite.\n\n{response.content}")],
        "patch_code": patch_code,
        "unit_test_code": test_code,
        "iteration_count": current_iter + 1
    }

