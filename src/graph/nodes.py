def get_base_llm():
    """Initializes the LLM based on environment settings."""
    provider = settings.get_resolved_provider()
    model_name = settings.get_resolved_model_name()
    temperature = settings.model_temperature

    if provider == "groq":
        return ChatGroq(
            model=model_name,
            temperature=temperature,
            groq_api_key=settings.groq_api_key
        )
    return ChatOpenAI(
        model=model_name,
        temperature=temperature,
        api_key=settings.openai_api_key
    )

llm = get_base_llm()

def get_current_date_str() -> str:
    """Returns dynamic current formatted date for temporal alignment."""
    return datetime.datetime.now().strftime("%B %d, %Y")

def extract_dynamic_code(text: str) -> dict:
    """Dynamically parses and extracts code blocks generated by the LLM with zero hardcoding."""
    blocks = re.findall(r'```(?:[a-zA-Z0-9_-]+)?\s*([\s\S]*?)```', text)
    if len(blocks) >= 2:
        return {"patch": blocks[0].strip(), "test": blocks[1].strip()}
    elif len(blocks) == 1:
        return {"patch": blocks[0].strip(), "test": "assert True"}
    else:
        # If no markdown blocks, dynamically use the model's raw text
        return {"patch": text.strip(), "test": text.strip()}

def detect_service_target(incident_text: str) -> str:
    """Dynamically identifies the target microservice from the incident text."""
    match = re.search(r'([\w-]+(?:api|service|db|worker|app|gateway))', incident_text, re.IGNORECASE)
    if match:
        return match.group(1).lower()
    return "checkout-api"

