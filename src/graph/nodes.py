# NODE 9: GIT PR & POST-MORTEM PUBLISHER (Deployment Node)
# =====================================================================
def deployment_and_postmortem_node(state: DevSecOpsState) -> dict:
    """Creates the GitHub Pull Request, triggers canary deployment, and publishes executive post-mortem."""
    patch = state.get("patch_code") or ""
    service = state.get("service_target") or "checkout-api"
    current_date = get_current_date_str()
    
    pr_result = create_github_pull_request.invoke({
        "repository_name": f"enterprise/{service}",
        "branch_name": f"hotfix/p0-{service}-remediation",
        "commit_message": f"fix({service}): database index optimization and latency remediation ({current_date})",
        "patch_content": patch
    })
    
    postmortem_prompt = f"""Synthesize a complete Executive Post-Mortem & Incident Resolution Report for {service}.
IMPORTANT TEMPORAL REQUIREMENT:
Today's Date is: {current_date}.
All generated deadlines, due dates, and prevention milestones MUST be realistic future dates relative to {current_date} (e.g. in the next 1-4 weeks).

Structure:
- 🚨 **Incident Overview & Business Impact** (504 Outage resolved on {current_date})
- 🔍 **Root Cause Summary** (Unindexed query causing high latency on 10,000-document dataset)
- 🛠️ **Remediation & Patch Details** (Compound index applied to live database)
- 🧪 **Verification Evidence** (Sandbox Unit Tests Passed, SAST Security Audit Zero High/Critical)
- 🚀 **Release & Pull Request** (Canary Fleet Deployed)
- 🛡️ **Long-Term Action Items Table** (Columns: #, Action Item, Owner, Due Date [relative to {current_date}], Status)"""

    response = llm.invoke([
        SystemMessage(content=f"You are the VP of Site Reliability Engineering. Current Date: {current_date}."),
        HumanMessage(content=postmortem_prompt)
    ])
    
    full_report = f"{pr_result}\n\n---\n\n{response.content}"

    return {
        "messages": [AIMessage(content=full_report)],
        "git_pr_url": f"https://github.com/enterprise/{service}/pull/4092",
        "post_mortem_report": full_report
    }

# =====================================================================
# CONDITIONAL ROUTING EDGES
# =====================================================================
def route_after_qa(state: DevSecOpsState) -> Literal["security_sast", "patch_engineer"]:
    """Self-healing loop: if QA tests fail, route back to Patch Engineer."""
    if not state.get("qa_passed", False) and (state.get("iteration_count", 0) < 3):
        return "patch_engineer"
    return "security_sast"

def route_after_security(state: DevSecOpsState) -> Literal["human_cab_gate", "patch_engineer"]:
    """Self-healing loop: if SAST security audit fails, route back to Patch Engineer."""
    if not state.get("security_passed", False) and (state.get("iteration_count", 0) < 3):
        return "patch_engineer"
    return "human_cab_gate"
